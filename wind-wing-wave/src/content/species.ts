/**
 * The species catalogue: the 93 real plants and animals that can find the islands.
 *
 * Every species is plain data: what it looks like (plant archetype or animal body plan, with its
 * own colours and size), what it sounds like, one true fact, its journal lines and field-guide
 * hints, and `eco`: what it needs to reach the islands and to stay (src/eco/needs.ts).
 *
 * The groups (field-guide tabs) and why each species is here:
 *   plants (36)  the land plants, in the order life really comes: rock pioneers (tints), ferns,
 *                grasses and beach plants, shrubs, trees, then pond and mangrove plants.
 *   sea (14)     sea plants (coralline algae, seagrass, coral) and sea animals, ending with the
 *                whales of the Sound (the ending) and the glowing plankton of a mangrove lagoon.
 *   birds (23)   seabirds first (the cliff, stack, islet and low-island birds), then shore and
 *                pond birds, then forest birds.
 *   small (12)   spiders, insects, a snail, crabs and brine shrimp.
 *   land (8)     lizards, a tortoise, a frog and the bats.
 * Every species has something you can see or hear (DECISIONS 11): a plant model or ground tint,
 * an animal, a voice, or a water effect (brine shrimp turn salt ponds pink; plankton glow).
 * There are no cave species, because the ground has no caves (DECISIONS 2).
 *
 * How to read the `eco` numbers (the shared assumptions with the ecology, WP-D1):
 *   - `rate` is arrival attempts per century at the reference island. At normal pace a century
 *     passes in 50 real seconds, so rate 2 means about one attempt every 25 s there. Small new
 *     islands get fewer attempts (the ecology's target effect), so the pioneers are fastest:
 *     spiders and spores (rate 9-14) land within seconds, beach plants (1-2.5) within minutes
 *     of a beach existing, seabirds (0.15-0.6) after a couple of minutes, land birds and rafts
 *     (0.1-0.5) much later. tools/simulate.ts tunes these against ARCHITECTURE §4.
 *   - Soil is in metres. Bare lava has none; lichens and crusts build a few millimetres a
 *     century, moss and ferns a few centimetres (gives.soil). The soil ladder sets the order on
 *     rock: lichen 0, moss 1 cm, ʻamaʻu fern 1.5 cm, grasses 3 cm, ʻaʻaliʻi 5 cm, ʻōhiʻa 7 cm,
 *     tree ferns 10 cm, koa 15 cm. Beach plants and palms root in bare sand (soil 0).
 *   - Moisture runs 0 (bone dry) .. 0.3 (a dry rain shadow) .. 0.5 (a low island) ..
 *     0.75 (the rainy windward side) .. 0.9 (cloud mist) .. 1 (standing water).
 *     Salt spray runs 1 at a windward waterline to 0 well inland.
 *   - Plants' `habitats` mean "this patch's habitat is one of these". Animals' `habitats` mean
 *     "the island has at least `minPatches` patches whose habitat is one of these". `places` and
 *     `requires` must all be present. No plant needs a habitat that only it can create.
 *   - `mainNeed` is the reason its first "couldn't stay" story gives; `text.seen` says the same
 *     thing in the species' own words.
 *
 * Ids are the array index (stable within a version; saves store keys, not ids). The order also
 * picks the "typical" species of each model for the renderer test fixtures, so the first species
 * of each archetype is its most common one.
 */
